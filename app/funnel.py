def funnel_v2_enabled() -> bool:
    return settings.client_funnel_version.strip().lower() == "v2"


def format_price() -> str:
    return f"{settings.platform_access_price_kzt:,}".replace(",", " ")


def registered_provider_line(language: str) -> str:
    status = settings.service_provider_status.strip().lower()
    if not any(marker in status for marker in ("ип", "жк", "индивидуаль")):
        return ""
    return (
        "✔ Орындаушы — тіркелген ЖК"
        if normalize_language(language) == "kz"
        else "✔ Исполнитель — зарегистрированный ИП"
    )


