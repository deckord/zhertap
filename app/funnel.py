def client_t(language: str | None, key: str, **values: object) -> str:
    from app.i18n import t

    selected = normalize_language(language)
    if funnel_v2_enabled() and key in V2_TRANSLATIONS[selected]:
        return V2_TRANSLATIONS[selected][key].format(**values)
    return t(selected, key, **values)


