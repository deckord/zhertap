def normalize_language(language: str | None) -> str:
    return "kz" if language == "kz" else "ru"


def t(language: str | None, key: str, **values: object) -> str:
    selected = normalize_language(language)
    return TRANSLATIONS[selected][key].format(**values)


def kazakh_region_label(row: dict) -> str:
    code = str(row.get("code") or "")
    name = KAZAKH_REGION_NAMES.get(code) or row.get("nameKz") or row.get("nameRu") or ""
    return f"{name} ({code})" if code and f"({code})" not in name else name
